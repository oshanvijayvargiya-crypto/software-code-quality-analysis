const AnalysisResult = require('../models/AnalysisResult');
const { analyzeCode: unifiedAnalyzeCode } = require('../services/analyzer/index');

exports.analyzeCode = async (req, res) => {
  try {
    let code = '';
    let language = 'JavaScript';
    let filename = 'untitled.js';

    // Handle File Upload vs Raw Text
    if (req.file) {
      code = req.file.buffer.toString('utf8');
      filename = req.file.originalname;
      if (filename.endsWith('.py')) language = 'Python';
      else if (filename.endsWith('.java')) language = 'Java';
    } else if (req.body.code) {
      code = req.body.code;
      language = req.body.language || 'JavaScript';
      filename = req.body.filename || 'pasted_code';
    } else {
      return res.status(400).json({ message: 'No code provided' });
    }

    let analysisResultData = null;

    try {
      analysisResultData = await unifiedAnalyzeCode(code, language);
    } catch (e) {
      return res.status(400).json({ message: e.message || 'Unsupported language' });
    }

    const newResult = new AnalysisResult({
      user: req.user.id,
      filename,
      language,
      metrics: analysisResultData.metrics,
      qualityScore: analysisResultData.qualityScore,
      issues: analysisResultData.issues
    });

    await newResult.save();

    res.json(newResult);
  } catch (err) {
    console.error('Error in analyzeCode:', err);
    res.status(500).send('Server Error during analysis');
  }
};

exports.getAnalyses = async (req, res) => {
  try {
    const results = await AnalysisResult.find({ user: req.user.id }).sort({ date: -1 });
    res.json(results);
  } catch (err) {
    console.error(err.message);
    res.status(500).send('Server Error');
  }
};

exports.getAnalysisById = async (req, res) => {
  try {
    const result = await AnalysisResult.findById(req.params.id);
    if (!result) {
      return res.status(404).json({ message: 'Analysis not found' });
    }
    // Check user
    if (result.user.toString() !== req.user.id) {
      return res.status(401).json({ message: 'User not authorized' });
    }
    res.json(result);
  } catch (err) {
    console.error(err.message);
    res.status(500).send('Server Error');
  }
};

exports.deleteAnalysis = async (req, res) => {
  try {
    const result = await AnalysisResult.findById(req.params.id);
    if (!result) {
      return res.status(404).json({ message: 'Analysis not found' });
    }
    // Check user
    if (result.user.toString() !== req.user.id) {
      return res.status(401).json({ message: 'User not authorized' });
    }
    await AnalysisResult.findByIdAndDelete(req.params.id);
    res.json({ message: 'Analysis removed' });
  } catch (err) {
    console.error(err.message);
    res.status(500).send('Server Error');
  }
};

const { generatePDF } = require('../services/pdfService');

exports.downloadPDF = async (req, res) => {
  try {
    const result = await AnalysisResult.findById(req.params.id);
    if (!result) {
      return res.status(404).json({ message: 'Analysis not found' });
    }
    // Check user
    if (result.user.toString() !== req.user.id) {
      return res.status(401).json({ message: 'User not authorized' });
    }
    
    // image generated by html2canvas can be passed in body
    const chartImage = req.body.chartImage;
    
    generatePDF(res, result, chartImage);
  } catch (err) {
    console.error(err.message);
    res.status(500).send('Server Error generating PDF');
  }
};
